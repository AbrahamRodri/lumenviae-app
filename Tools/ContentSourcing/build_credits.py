#!/usr/bin/env python3
"""Write app/Data/SourcesAndCredits.swift from sources.py: the paintings
the app bundles (the mysteries', the chants' and the Prayer Book's), the
texts it bundles or fetches, and the recordings, each with its maker,
edition and licence, for the Sources & Credits page under About.

    python3 build_credits.py

Run it after fetch.py and build_manifest.py, so a painting taken is
credited. A painting is listed only when its imageset is on disk.
"""

import json
from pathlib import Path

import sources as S

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ASSETS = ROOT / "app" / "Assets.xcassets"
OUT = ROOT / "app" / "Data" / "SourcesAndCredits.swift"


def esc(s):
    return (s or "").replace("\\", "\\\\").replace('"', '\\"')


def paintings():
    rows = []
    fetched = json.loads((HERE / "fetched.json").read_text()) if (HERE / "fetched.json").exists() else {}
    for name, work, creator, date, collection, status in S.EXISTING:
        if not (ASSETS / f"{name}.imageset").exists():
            continue
        prov = S.PROVENANCE.get(name, {})
        # A painting never identified has no licence read off a source page
        fallback = "Public domain" if status == "confirmed" else "Probably public domain (source not established)"
        rows.append((name, work, creator or "Painter not established", date, collection, prov.get("licence") or fallback))
    for p in S.PAINTINGS:
        name = p["imageset"]
        if p.get("alias_of") or not (ASSETS / f"{name}.imageset").exists():
            continue
        got = fetched.get(name, {})
        rows.append((name, p["work"], p["creator"], p.get("date"), p.get("collection"), got.get("licence") or p["licence"]))
    # The mysteries' paintings first, in the order the Rosary prays them
    order = ["joyful_annunciation", "joyful_visitation", "joyful_nativity", "joyful_presentation", "joyful_finding",
             "sorrowful_agony", "sorrowful_scourging", "sorrowful_crowning", "sorrowful_carrying", "sorrowful_crucifixion",
             "glorious_resurrection", "glorious_ascension", "glorious_pentecost", "glorious_assumption", "glorious_coronation",
             "luminous_baptism", "luminous_cana", "luminous_proclamation", "luminous_transfiguration", "luminous_eucharist",
             "seven_sorrows_simeon", "seven_sorrows_flight", "seven_sorrows_finding", "seven_sorrows_meeting",
             "seven_sorrows_calvary", "seven_sorrows_descent", "seven_sorrows_burial", "seven_sorrows_pieta"]
    def key(r):
        return (order.index(r[0]), "") if r[0] in order else (len(order), r[0])
    return sorted(rows, key=key)


def build():
    lines = ['//',
             '//  SourcesAndCredits.swift',
             '//  Lumen Viae',
             '//',
             '//  GENERATED by Tools/ContentSourcing/build_credits.py from sources.py:',
             '//  every painting the app bundles, the texts it bundles or fetches, and',
             '//  the recordings, each with its maker, edition and licence, for the',
             '//  Sources & Credits page under About. Edit sources.py and rerun;',
             '//  never hand-edit this file.',
             '//',
             '',
             'import Foundation',
             '',
             '/// One work the app uses that is not its own: a painting, a text, a',
             '/// recording, a typeface.',
             'struct CreditedWork: Identifiable, Hashable {',
             '    /// The work\'s name, as its maker or museum names it',
             '    let title: String',
             '    /// Who made it, and the edition or translation where there is one',
             '    let maker: String',
             '    /// Where it stands in the app, or the date and collection of a painting',
             '    let detail: String',
             '    /// The terms it is used under',
             '    let licence: String',
             '',
             '    var id: String { title + maker }',
             '}',
             '',
             'enum SourcesAndCredits {',
             '',
             '    /// The paintings, the mysteries\' first in the order the Rosary prays',
             '    /// them, then the rest of the app\'s',
             '    static let paintings: [CreditedWork] = [']
    for name, work, creator, date, collection, licence in paintings():
        detail = ", ".join(x for x in [date, collection] if x)
        lines.append(f'        CreditedWork(title: "{esc(work)}", maker: "{esc(creator)}", detail: "{esc(detail)}", licence: "{esc(licence)}"),')
    lines[-1] = lines[-1].rstrip(',')
    lines += ['    ]', '', '    /// The texts, the recordings, the type and the glyphs', '    static let texts: [CreditedWork] = [']
    for t in S.TEXTS:
        lines.append(f'        CreditedWork(title: "{esc(t["title"])}", maker: "{esc(t["maker"])}", detail: "{esc(t["detail"])}. {esc(t["source"])}.", licence: "{esc(t["licence"])}"),')
    lines[-1] = lines[-1].rstrip(',')
    lines += ['    ]', '}', '']
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: {len(paintings())} paintings, {len(S.TEXTS)} texts")


if __name__ == "__main__":
    build()
